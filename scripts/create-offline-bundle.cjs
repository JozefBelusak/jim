const { createHash } = require('node:crypto');
const { readdirSync, readFileSync, writeFileSync } = require('node:fs');
const path = require('node:path');

const outputDirectory = path.resolve(process.argv[2] || path.join(process.cwd(), 'dist'));
const staticExtensions = new Set(['.js', '.css', '.png', '.jpg', '.jpeg', '.svg', '.gif', '.webp', '.ico', '.woff', '.woff2', '.ttf', '.otf', '.wasm', '.webmanifest']);

function listStaticFiles(directory, prefix = '') {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      return listStaticFiles(path.join(directory, entry.name), relative);
    }
    return relative === 'index.html' || (relative !== 'sw.js' && staticExtensions.has(path.extname(entry.name))) ? [relative] : [];
  });
}

const files = listStaticFiles(outputDirectory).sort();
if (!files.includes('index.html') || !files.some((file) => file.startsWith('_expo/') && file.endsWith('.js'))) {
  throw new Error('Offline bundle needs an Expo web export with index.html and its compiled JavaScript.');
}
const versionHash = createHash('sha256');
versionHash.update(readFileSync(path.resolve(process.argv[1])));
for (const file of files) {
  versionHash.update(file);
  versionHash.update(readFileSync(path.join(outputDirectory, file)));
}
const cacheName = `jimrat-static-${versionHash.digest('hex').slice(0, 20)}`;
const assetPaths = files.map((file) => `/${file.split('/').map(encodeURIComponent).join('/')}`);

const worker = `/* Generated from the exported web assets. Do not edit this file directly. */
'use strict';
const CACHE_PREFIX = 'jimrat-static-';
const CACHE_NAME = ${JSON.stringify(cacheName)};
const ASSET_PATHS = ${JSON.stringify(assetPaths)};
const APP_NAVIGATION_PATHS = new Set(['/', '/index.html']);
const assetUrls = new Set(ASSET_PATHS.map((assetPath) => new URL(assetPath, self.location.origin).href));

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      await cache.addAll(ASSET_PATHS.map((assetPath) => new Request(assetPath, { cache: 'reload' })));
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
    // Keep a new version waiting until every tab using the old worker is closed.
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map((name) => caches.delete(name)));
    // Do not claim or reload an open workout.
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate' && APP_NAVIGATION_PATHS.has(url.pathname)) {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok) return response;
      } catch {
        // Network unavailable: use a complete, matching installed version.
      }
      const cache = await caches.open(CACHE_NAME);
      const fallback = await cache.match('/index.html');
      return fallback || new Response('The app has not finished preparing offline access. Open it once while online.', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
    })());
    return;
  }

  // Only the generated static manifest is cached. API requests, external media
  // and user export/download URLs go directly to the browser network.
  if (url.search || !assetUrls.has(url.href)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(request);
    return cached || fetch(request);
  })());
});
`;

writeFileSync(path.join(outputDirectory, 'sw.js'), worker);
process.stdout.write(`Offline bundle: ${files.length} assets, ${cacheName}\n`);
